// Command gen writes internal/app/modules_gen.go by scanning module folders.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	root, err := findRoot()
	if err != nil {
		fail(err)
	}
	modulePath, err := readModulePath(filepath.Join(root, "go.mod"))
	if err != nil {
		fail(err)
	}
	modulesDir := filepath.Join(root, "internal", "modules")
	entries, err := os.ReadDir(modulesDir)
	if err != nil {
		fail(err)
	}
	var names []string
	for _, entry := range entries {
		if !entry.IsDir() {
			continue
		}
		name := entry.Name()
		if strings.HasPrefix(name, "_") || name == "gen" {
			continue
		}
		if _, err := os.Stat(filepath.Join(modulesDir, name, "module.go")); err != nil {
			continue
		}
		names = append(names, name)
	}
	sort.Strings(names)

	var buf bytes.Buffer
	buf.WriteString("// Code generated by go generate; DO NOT EDIT.\n")
	buf.WriteString("package app\n\n")
	if len(names) == 0 {
		buf.WriteString("// Tidak ada modul terpasang.\n")
	} else {
		buf.WriteString("import (\n")
		for _, name := range names {
			fmt.Fprintf(&buf, "\t_ %q\n", modulePath+"/internal/modules/"+name)
		}
		buf.WriteString(")\n")
	}
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		fail(err)
	}
	out := filepath.Join(root, "internal", "app", "modules_gen.go")
	if err := os.WriteFile(out, formatted, 0o644); err != nil {
		fail(err)
	}
	fmt.Printf("modules_gen.go: %d modul (%s)\n", len(names), strings.Join(names, ", "))
}

func findRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("go.mod tidak ditemukan dari %s", dir)
		}
		dir = parent
	}
}

func readModulePath(gomod string) (string, error) {
	data, err := os.ReadFile(gomod)
	if err != nil {
		return "", err
	}
	for _, line := range strings.Split(string(data), "\n") {
		fields := strings.Fields(line)
		if len(fields) >= 2 && fields[0] == "module" {
			return fields[1], nil
		}
	}
	return "", fmt.Errorf("module path tidak ditemukan di go.mod")
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "gen:", err)
	os.Exit(1)
}
